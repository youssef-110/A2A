/** Lit cells of a glyph as [col, row] pairs. */
const cache = new Map();
export function glyph(ch) {
  const key = ch.toUpperCase();
  if (!cache.has(key)) {
    const rows = ROWS[key]?.split("|") ?? [];
    const lit = [];
    rows.forEach((r, y) => [...r].forEach((c, x) => c === "#" && lit.push([x, y])));
    cache.set(key, lit);
  }
  return cache.get(key);
}

/** Lit cells of a whole string, 6 columns per character (5 for the glyph, 1 gap). */
export function textCells(text) {
  const out = [];
  [...text].forEach((ch, i) => glyph(ch).forEach(([x, y]) => out.push([i * 6 + x, y, i])));
  return out;
}
